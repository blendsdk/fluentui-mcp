/**
 * The explicit source→destination mapping for the generated skill tree.
 *
 * One enhanced schema becomes a set of {@link SkillFile} objects held entirely
 * in memory. The writer never touches the filesystem until every id has passed
 * the safety checks, so an unsafe or malformed schema cannot leave a partial
 * tree behind.
 *
 * The mapping is deliberately a plain table of rules rather than a generic
 * templating system: each schema section has exactly one destination folder,
 * and the file name is the entity's own id. That keeps the output diffable and
 * makes the drift gate a byte comparison.
 *
 * Destination layout (relative to the skill root):
 * `references/{index.md, foundation/<id>.md, components/<id>.md,
 * categories/<category>.md, recipes/<group>/<id>.md, quick-reference/<id>.md}`.
 *
 * @module skill/mapping
 */

import type {
  CategoryGuidanceEntry,
  ComponentEntry,
  FluentUISchema,
  GuideEntry,
  RecipeEntry,
} from '../../src/types/schema.js';
import { renderPropsReference } from './render/props.js';
import { renderExamplesSection } from './render/stories.js';
import {
  appendMarker,
  bulletList,
  bulletSection,
  escapeLinkLabel,
  escapeTableCell,
  fencedCode,
  heading,
  inlineCode,
  joinSections,
  proseSection,
  table,
} from './render/sections.js';

/** The skill name; it is also the directory name under `.agents/skills/`. */
export const SKILL_NAME = 'fluentui';

/** Marker appended to every generated file so hand-written files stand out. */
export const GENERATED_MARKER =
  '<!-- Generated by scripts/skill/generate.ts — do not edit by hand. -->';

/** Folder, relative to the skill root, that holds all generated references. */
export const REFERENCE_DIR = 'references';

/**
 * Fixed order of recipe groups.
 *
 * Recipe files live under `references/recipes/<group>/`, and grouping them in
 * this order keeps the tree stable even when recipes are added or removed.
 */
export const RECIPE_GROUP_ORDER = [
  'forms',
  'data',
  'navigation',
  'modals',
  'layout',
  'state',
  'accessibility',
] as const;

/** A single generated file, with a POSIX-style path relative to the skill root. */
export interface SkillFile {
  /** Relative destination path, for example `references/components/button.md`. */
  path: string;

  /** Complete UTF-8 file content, ending with the generated marker. */
  content: string;
}

/**
 * Render-time identifiers recorded in the provenance section.
 *
 * These values are not part of the schema, so they are threaded in explicitly:
 * the skill version comes from `package.json`, the generator version from this
 * codebase, and the schema hash from the manifest. Keeping them out of the
 * schema preserves the determinism promise — identical inputs, identical
 * bytes — because none of them is a wall-clock value.
 */
export interface SkillRenderContext {
  /** Published version of the fluentui-skill package (from package.json). */
  skillVersion: string;

  /** Version of the generator that produced the tree. */
  generatorVersion: string;

  /** SHA-256 of the input schema, as recorded in the manifest. */
  schemaHash: string;
}

/**
 * Safe id pattern: lowercase kebab-case.
 *
 * Ids become file and directory names, so the pattern permits only `a-z`, `0-9`,
 * and single hyphens. It cannot express `..`, `/`, or a drive/absolute prefix,
 * which closes the path-traversal risk at the source.
 */
const SAFE_ID_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

/**
 * True when an id is safe to use as a single path component.
 *
 * @param id - Candidate id.
 * @returns True for a non-empty lowercase kebab-case id.
 */
export function isSafeSkillId(id: string): boolean {
  return typeof id === 'string' && SAFE_ID_PATTERN.test(id);
}

/** Throw a descriptive error when an id is not path-safe. */
function assertSafeId(kind: string, id: string): void {
  if (!isSafeSkillId(id)) {
    throw new Error(
      `Unsafe ${kind} id "${id}": ids must be lowercase kebab-case and may not contain "/" or "..".`,
    );
  }
}

/** Normalize line endings and append the generated marker. */
function finalize(markdown: string): string {
  const normalized = markdown.replace(/\r\n?/g, '\n').trimEnd();
  return appendMarker(normalized, GENERATED_MARKER);
}

/**
 * Drop a leading level-1 heading from authored content.
 *
 * Guide and recipe prose often starts with its own `# Title`. The renderer
 * adds a title from the schema, so keeping both would produce two H1s. Removing
 * the embedded one keeps a single document title and consistent metadata.
 */
function stripLeadingHeading(content: string): string {
  return content.replace(/^\s*#\s+[^\n]*\n+/, '').trim();
}

