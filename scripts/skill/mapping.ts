/**
 * Render the identity header of a component file: name, package, import,
 * category, stability, and a deprecation warning when applicable.
 */
function renderComponentHeader(component: ComponentEntry): string {
  const lines = [heading(1, component.name), ''];
  if (component.deprecated) {
    const message = component.deprecationMessage
      ? `: ${component.deprecationMessage}`
      : '';
    lines.push(`> ⚠️ **Deprecated**${message}`, '>');
  }
  const version = component.packageVersion ? ` v${component.packageVersion}` : '';
  lines.push(
    `> **Package**: \`${component.packageName}\`${version}`,
    `> **Import**: \`${component.importStatement}\``,
    `> **Category**: ${component.category}`,
    `> **Stability**: ${component.stability}`,
  );
  return lines.join('\n');
}

/** Render the overview prose, falling back to a neutral line for raw entries. */
function renderComponentOverview(component: ComponentEntry): string {
  const description = component.enhanced?.description?.trim();
  const whenToUse = component.enhanced?.whenToUse?.trim();
  const body =
    description && description !== ''
      ? description
      : `${component.name} is part of the \`${component.packageName}\` package.`;
  return joinSections([
    heading(2, 'Overview'),
    body,
    whenToUse ? `**When to use**: ${whenToUse}` : '',
  ]);
}

/** Render the Do's and Don'ts section from enhanced content. */
function renderBestPractices(component: ComponentEntry): string {
  const best = component.enhanced?.bestPractices;
  if (!best || (best.dos.length === 0 && best.donts.length === 0)) {
    return '';
  }
  return joinSections([
    heading(2, 'Best Practices'),
    best.dos.length > 0 ? joinSections([heading(3, "Do's"), bulletList(best.dos)]) : '',
    best.donts.length > 0 ? joinSections([heading(3, "Don'ts"), bulletList(best.donts)]) : '',
  ]);
}

/** Render anti-patterns: each mistake paired with its correct approach. */
function renderAntiPatterns(component: ComponentEntry): string {
  const items = component.enhanced?.antiPatterns;
  if (!items || items.length === 0) {
    return '';
  }
  const blocks = items.map((item) =>
    joinSections([
      heading(3, item.title),
      `❌ ${item.problem}`,
      `✅ ${item.solution}`,
    ]),
  );
  return joinSections([heading(2, 'Anti-Patterns'), ...blocks]);
}

/** Render accessibility guidance: requirements, keyboard table, ARIA, screen reader. */
function renderAccessibility(component: ComponentEntry): string {
  const a11y = component.enhanced?.accessibility;
  if (!a11y) {
    return '';
  }
  const keyboard =
    a11y.keyboardSupport.length > 0
      ? table(
          ['Key', 'Action'],
          a11y.keyboardSupport.map((entry) => [
            inlineCode(entry.key),
            escapeTableCell(entry.action),
          ]),
        )
      : '';
  return joinSections([
    heading(2, 'Accessibility'),
    a11y.requirements ? `**Requirements**: ${a11y.requirements.trim()}` : '',
    keyboard,
    a11y.ariaAttributes.length > 0
      ? `**ARIA**: ${a11y.ariaAttributes.join(', ')}`
      : '',
    a11y.screenReaderBehavior
      ? `**Screen Reader**: ${a11y.screenReaderBehavior.trim()}`
      : '',
  ]);
}

/** Render the links footer: the component's category and related recipes. */
function renderComponentLinks(
  component: ComponentEntry,
  categoryIds: ReadonlySet<string>,
  recipeGroups: ReadonlyMap<string, string>,
): string {
  const links: string[] = [];
  if (categoryIds.has(component.category)) {
    const label = escapeLinkLabel(`${component.category} category`);
    links.push(`[${label}](../categories/${component.category}.md)`);
  }
  for (const recipeId of component.enhanced?.relatedRecipes ?? []) {
    const group = recipeGroups.get(recipeId);
    if (group) {
      const label = escapeLinkLabel(`${recipeId} recipe`);
      links.push(`[${label}](../recipes/${group}/${recipeId}.md)`);
    }
  }
  if (component.relatedComponents.length > 0) {
    links.push(
      ...component.relatedComponents.map((name) =>
        name.replace(/\r?\n/g, ' ').trim(),
      ),
    );
  }
  if (links.length === 0) {
    return '';
  }
  return joinSections([heading(2, 'See Also'), bulletList(links)]);
}

/**
 * Render one component reference file from its scraped data and prose.
 *
 * Examples come only from story code; every other section is additive and is
 * omitted when its source field is missing.
 */
function renderComponentFile(
  component: ComponentEntry,
  categoryIds: ReadonlySet<string>,
  recipeGroups: ReadonlyMap<string, string>,
): string {
  return finalize(
    joinSections([
      renderComponentHeader(component),
      renderComponentOverview(component),
      renderPropsReference(component),
      renderExamplesSection(component),
      renderBestPractices(component),
      renderAntiPatterns(component),
      renderAccessibility(component),
      proseSection('Styling', component.enhanced?.stylingTips),
      proseSection('Performance', component.enhanced?.performanceNotes),
      proseSection('Theming & Tokens', component.enhanced?.themingNotes),
      proseSection('Migration Notes', component.enhanced?.migrationNotes),
      bulletSection('Edge Cases', component.enhanced?.edgeCases),
      renderComponentLinks(component, categoryIds, recipeGroups),
    ]),
  );
}

/** Render a foundation or quick-reference guide file. */
function renderGuideFile(guide: GuideEntry): string {
  const examples = guide.codeExamples
    .map((example) =>
      joinSections([
        heading(3, example.title),
        example.description?.trim() ?? '',
        fencedCode(example.code, example.language || 'tsx'),
      ]),
    );
  return finalize(
    joinSections([
      heading(1, guide.title),
      guide.category ? `> **Category**: ${guide.category}` : '',
      guide.content ? stripLeadingHeading(guide.content) : '',
      bulletSection('Key Takeaways', guide.keyTakeaways),
      examples.length > 0
        ? joinSections([heading(2, 'Examples'), ...examples])
        : '',
      bulletSection('Pitfalls', guide.pitfalls),
      proseSection('Accessibility', guide.accessibilityNotes),
      guide.referencedComponents.length > 0
        ? `**Referenced components**: ${guide.referencedComponents.join(', ')}`
        : '',
    ]),
  );
}

/** Render a category guidance file, including links to its components. */
function renderCategoryFile(
  category: CategoryGuidanceEntry,
  components: ReadonlyMap<string, ComponentEntry>,
): string {
  const componentLinks = category.componentIds
    .filter((id) => components.has(id))
    .map((id) => {
      const label = escapeLinkLabel(components.get(id)?.name ?? id);
      return `[${label}](../components/${id}.md)`;
    });
  return finalize(
    joinSections([
      heading(1, `${category.category} components`),
      heading(2, 'Overview'),
      category.overview,
      proseSection('When to Use', category.whenToUse),
      renderCategoryBestPractices(category),
      renderCategoryAntiPatterns(category),
      proseSection('Accessibility', category.accessibility),
      componentLinks.length > 0
        ? joinSections([
            heading(2, 'Components in this category'),
            bulletList(componentLinks),
          ])
        : '',
    ]),
  );
}

/** Render a category's shared Do's and Don'ts. */
function renderCategoryBestPractices(category: CategoryGuidanceEntry): string {
  const { dos, donts } = category.bestPractices;
  if (dos.length === 0 && donts.length === 0) {
    return '';
  }
  return joinSections([
    heading(2, 'Best Practices'),
    dos.length > 0 ? joinSections([heading(3, "Do's"), bulletList(dos)]) : '',
    donts.length > 0 ? joinSections([heading(3, "Don'ts"), bulletList(donts)]) : '',
  ]);
}

/** Render a category's shared anti-patterns. */
function renderCategoryAntiPatterns(category: CategoryGuidanceEntry): string {
  if (category.antiPatterns.length === 0) {
    return '';
  }
  const blocks = category.antiPatterns.map((item) =>
    joinSections([
      heading(3, item.title),
      `❌ ${item.problem}`,
      `✅ ${item.solution}`,
    ]),
  );
  return joinSections([heading(2, 'Anti-Patterns'), ...blocks]);
}

/** Render a recipe file from its prose, examples, and cross-links. */
function renderRecipeFile(
  recipe: RecipeEntry,
  components: ReadonlyMap<string, ComponentEntry>,
): string {
  // `components` is keyed by lowercased component name; recipes reference
  // components by display name rather than by id.
  const examples = recipe.examples
    .map((example) =>
      joinSections([
        heading(3, example.name),
        example.description?.trim() ?? '',
        fencedCode(example.code, example.language || 'tsx'),
      ]),
    );
  const componentLinks = recipe.referencedComponents
    .map((name) => components.get(name.trim().toLowerCase()))
    .filter((component): component is ComponentEntry => component !== undefined)
    .map((component) => {
      const label = escapeLinkLabel(component.name);
      return `[${label}](../../components/${component.id}.md)`;
    });
  return finalize(
    joinSections([
      heading(1, recipe.title),
      `> **Group**: ${recipe.group}`,
      proseSection('Goal', recipe.goal),
      proseSection('When to Use', recipe.whenToUse),
      proseSection('When Not to Use', recipe.whenNotToUse),
      recipe.content ? stripLeadingHeading(recipe.content) : '',
      examples.length > 0
        ? joinSections([heading(2, 'Examples'), ...examples])
        : '',
      bulletSection('Pitfalls', recipe.pitfalls),
      proseSection('Accessibility', recipe.accessibilityNotes),
      componentLinks.length > 0
        ? joinSections([
            heading(2, 'Components used'),
            bulletList(componentLinks),
          ])
        : '',
    ]),
  );
}

/**
 * Format the package versions that the scraped components come from as a
 * compact range and count.
 *
 * Counting is per package, not per component: many components share one package
 * (the Button family, for example), so counting entries would overstate how many
 * packages the snapshot covers. Only plain `x.y.z` versions are considered;
 * prerelease or malformed values are ignored so a single odd value cannot
 * distort the range. Comparison is numeric by major, then minor, then patch, so
 * `9.10.0` sorts above `9.2.0` rather than being compared as text.
 *
 * @param components - Component entries carrying `packageName`/`packageVersion`
 * @returns For example `2 packages, 9.2.0–9.10.0`, or undefined when none
 */
export function formatPackageVersionRange(
  components: readonly ComponentEntry[],
): string | undefined {
  // Map each package to one parsed version. Taking the first valid version per
  // package keeps the result deterministic for a given schema.
  const versionByPackage = new Map<string, number[]>();
  for (const component of components) {
    if (versionByPackage.has(component.packageName)) {
      continue;
    }
    const parsed = parsePlainVersion(component.packageVersion);
    if (parsed) {
      versionByPackage.set(component.packageName, parsed);
    }
  }

  const versions = [...versionByPackage.values()];
  if (versions.length === 0) {
    return undefined;
  }

  const sorted = [...versions].sort(compareVersions);
  const min = formatVersion(sorted[0]);
  const max = formatVersion(sorted[sorted.length - 1]);
  const noun = versions.length === 1 ? 'package' : 'packages';
  const range = min === max ? min : `${min}–${max}`;

  return `${versions.length} ${noun}, ${range}`;
}

/**
 * Parse a plain `x.y.z` version into its numeric parts.
 *
 * @param version - Candidate version string
 * @returns The three numeric parts, or undefined when not plain semver
 */
function parsePlainVersion(version: string): number[] | undefined {
  const match = /^(\d+)\.(\d+)\.(\d+)$/.exec(version);
  if (!match) {
    return undefined;
  }
  return [Number(match[1]), Number(match[2]), Number(match[3])];
}

/**
 * Compare two parsed versions by major, minor, then patch.
 *
 * @param a - First parsed version
 * @param b - Second parsed version
 * @returns A negative, zero, or positive number following `Array#sort` rules
 */
function compareVersions(a: number[], b: number[]): number {
  for (let index = 0; index < 3; index += 1) {
    const difference = a[index] - b[index];
    if (difference !== 0) {
      return difference;
    }
  }
  return 0;
}

/** Render a parsed version back to `x.y.z`. */
function formatVersion(parts: number[]): string {
  return parts.join('.');
}

/**
 * Render the "Source & versions" provenance section.
 *
 * The section lists the FluentUI source ref and commit, the umbrella package
 * version when present, the component package version range, and the skill,
 * generator, and schema identifiers. It deliberately excludes any timestamp so
 * generated references stay reproducible.
 *
 * Rows whose data is absent are omitted. The schema is validated before
 * rendering, so `sources.fluentui` is always present.
 *
 * @param schema - The enhanced schema
 * @param context - Skill version, generator version, and schema hash
 * @returns A Markdown section
 */
function renderProvenance(
  schema: FluentUISchema,
  context: SkillRenderContext,
): string {
  const source = schema.sources.fluentui;
  const rows: string[][] = [
    ['Fluent UI version', escapeTableCell(schema.version)],
    [
      'Fluent UI source',
      `${inlineCode(source.ref)} @ ${inlineCode(source.commit.slice(0, 7))}`,
    ],
  ];

  if (source.packageName && source.packageVersion) {
    rows.push([
      'Umbrella package',
      `${inlineCode(source.packageName)} ${escapeTableCell(source.packageVersion)}`,
    ]);
  }

  const range = formatPackageVersionRange(schema.components ?? []);
  if (range) {
    rows.push(['Component packages', escapeTableCell(range)]);
  }

  rows.push(
    ['Skill version', escapeTableCell(context.skillVersion)],
    ['Generator', escapeTableCell(context.generatorVersion)],
    ['Schema hash', inlineCode(context.schemaHash.slice(0, 12))],
  );

  return joinSections([
    heading(2, 'Source & versions'),
    table(['Item', 'Value'], rows),
  ]);
}

/** Render the routing index: task→recipe map, category index, and all references. */
function renderIndexFile(
  schema: FluentUISchema,
  orderedRecipes: readonly RecipeEntry[],
  orderedComponents: readonly ComponentEntry[],
  context: SkillRenderContext,
): string {
  const taskTable = table(
    ['Task', 'Recipe', 'Group'],
    orderedRecipes.map((recipe) => [
      escapeTableCell(recipe.title),
      `[${escapeLinkLabel(recipe.id)}](recipes/${recipe.group}/${recipe.id}.md)`,
      escapeTableCell(recipe.group),
    ]),
  );

  const categoryTable = table(
    ['Category', 'Components'],
    schema.categoryGuidance.map((category) => [
      `[${escapeLinkLabel(category.category)}](categories/${category.id}.md)`,
      String(category.componentIds.length),
    ]),
  );

  return finalize(
    joinSections([
      heading(1, 'FluentUI reference index'),
      'Hand-written routing lives in `SKILL.md`; this file indexes every generated reference.',
      renderProvenance(schema, context),
      heading(2, 'Task → recipe'),
      taskTable,
      heading(2, 'Categories'),
      categoryTable,
      heading(2, 'Foundation'),
      bulletList(
        schema.foundation.map(
          (guide) =>
            `[${escapeLinkLabel(guide.title)}](foundation/${guide.id}.md)`,
        ),
      ),
      heading(2, 'Components'),
      bulletList(
        orderedComponents.map(
          (component) =>
            `[${escapeLinkLabel(component.name)}](components/${component.id}.md)`,
        ),
      ),
      heading(2, 'Quick reference'),
      bulletList(
        schema.quickReference.map(
          (guide) =>
            `[${escapeLinkLabel(guide.title)}](quick-reference/${guide.id}.md)`,
        ),
      ),
    ]),
  );
}

